function whoHeIsNow(character, season, age, preview) {
  const card = el('section', { class: 'cv-card' });
  const klass = classify(character.ratings || {}, character.position);
  const inches = heightNow(character, season);

  const head = el('div', { class: 'cv-card-head' },
    el('h2', {},
      (character.jersey_preference === null || character.jersey_preference === undefined
        ? '' : `#${character.jersey_preference} `)
      + `${character.first_name} ${character.last_name}`),
    statusPill(character.status));
  if (character.league) {
    head.append(el('span', { class: 'cv-pill' },
      LEAGUE_LABELS[character.league] || character.league));
  }
  if (preview) head.append(el('span', { class: 'cv-pill' }, 'example'));
  card.append(head);

  card.append(el('p', { class: 'cv-muted' }, describeCharacter(character, season)));

  card.append(el('div', { class: 'cv-readout cv-cheese' },
    el('b', {}, classLine(klass)),
    el('span', {}, klass.blurb),
    el('span', {}, `Second closest: ${klass.runnerUp.label}. The label is read off his sheet `
      + 'every time this page loads, so it moves as he does.')));

  /* dt/dd are wrapped a pair at a time: a <dl> laid out as a grid puts every dt and every dd in
     a cell of its own, which scatters the labels away from their values. A <div> around each
     pair is valid inside a <dl> and is what keeps them together. */
  const facts = el('dl', { class: 'cv-facts' });
  const fact = (term, value) => {
    if (value === null || value === undefined || value === '') return;
    facts.append(el('div', { class: 'cv-fact' }, el('dt', {}, term), el('dd', {}, value)));
  };

  fact('Age', String(age));
  fact('Height now', inches ? formatHeight(inches) : '—');
  // What the save holds now, on the same curve the commissioner writes each offseason: his
  // frame at this year's height and age, plus the number he chose at fourteen as an offset.
  // Characters made before the weight column existed have no choice recorded, so their build
  // stands in for one - weightAt() handles that, and it is why this is never blank.
  const weighsNow = Number(character.weight_lbs) || weightAt(character, inches || character.height_inches, age);
  fact('Weight', `${weighsNow} lbs`
    + (character.weight_lbs && weighsNow !== character.weight_lbs
      ? ` · ${character.weight_lbs} at ${START_AGE}` : ''));
  fact('Build', character.build ? (buildOption(character.build) || {}).label : null);
  fact('Listed at', POSITION_LABELS[character.position] || character.position);
  fact('Reads as', klass.label);
  fact('Team', character.team_abbrev || 'no roster spot yet');
  fact('League', LEAGUE_LABELS[character.league] || character.league || '—');
  fact('Hometown', character.hometown || null);
  fact('Born', character.game_dob ? fmtDate(character.game_dob) : 'no in-game birthday yet');
  fact('Created', character.created_at ? fmtDate(character.created_at) : null);
  card.append(facts);

  card.append(el('p', { class: 'cv-muted' }, positionLine(character)));

  const goal = goalLine(character.career_goal);
  if (goal) card.append(el('p', {}, el('b', {}, 'What he wants: '), goal));

  if (character.traits && Object.keys(character.traits).length) {
    const traits = el('div', { class: 'cv-traits' });
    renderTraitBars(traits, character.traits);
    card.append(el('h3', {}, 'What the quiz said about him, and still says'), traits);
  }

  return card;
}

/* --------------------------------------------------------------------------- the arc */

/**
 * The levels he has been through, as a normalised list the renderer can draw either way.
 *
 * `character.level_history` is the column that would make this complete: an array of
 * {level, team_abbrev, player_id, from_season, to_season, from_age, to_age, how_it_ended}.
 * Nothing writes it yet. Until it exists, only three facts are actually known - he started in
 * Prep at fourteen, he is in `league` now, and he is `age` - so the levels below his current
 * one are marked "came through, years not recorded" rather than given invented dates.
 */
function levelTrack(character, season, age) {
  const here = LEVEL_INDEX[character.league];
  const current = here === undefined ? 0 : here;
  const stored = Array.isArray(character.level_history) ? character.level_history : null;

  return LEVELS.map((level, i) => {
    const row = stored ? stored.find((h) => h && h.level === level.key) : null;
    const state = i < current ? 'done' : i === current ? 'now' : 'ahead';
    const years = row && Number.isFinite(Number(row.to_season)) && Number.isFinite(Number(row.from_season))
      ? Math.max(1, Number(row.to_season) - Number(row.from_season) + 1)
      : null;
    return {
      ...level,
      state,
      row,
      years,
      team: row ? row.team_abbrev : (state === 'now' ? character.team_abbrev : null),
      playerId: playerIdFor(character, level.key, row),
      // Only the level he is standing in has a season we can name, and only if he has a birthday.
      season: state === 'now' && season && character.game_dob ? Number(season) : null,
      age: state === 'now' && character.game_dob ? age : null,
    };
  });
}

function theArc(character, season, age) {
  const card = el('section', { class: 'cv-card' });
  card.append(el('div', { class: 'cv-card-head' },
    el('h2', {}, 'The arc'),
    el('span', { class: 'cv-muted' }, 'prep, college, pro - one character, three saves')));

  const track = levelTrack(character, season, age);
  const known = track.some((t) => t.years);

  /* The shape, at a glance. Each level is a segment; when level_history arrives the segments are
     sized by the years actually spent there, so "four years of prep, two of college" reads off
     the widths. Until then they are even thirds and the colour carries the whole message. */
  const rail = el('ol', { class: 'cv-arc' });
  for (const t of track) {
    rail.append(el('li', {
      class: `cv-arc-step is-${t.state}`,
      style: `flex-grow:${t.years || 1}`,
    },
    el('b', {}, t.label),
    el('span', {}, t.years
      ? `${t.years} ${t.years === 1 ? 'season' : 'seasons'}`
      : t.state === 'now' ? 'here now' : t.state === 'done' ? 'came through' : 'ahead of him'),
    /* "team not recorded" is only true of a level he has LEFT. A character still waiting for a
       roster spot has no team because there is nothing to record yet, which is a different
       sentence. */
    el('em', {}, t.team
      || (t.state === 'ahead' ? '' : t.state === 'now' ? 'no roster spot yet' : 'team not recorded'))));
  }
  card.append(rail);
  if (!known) {
    card.append(el('p', { class: 'cv-hint' },
      'The segments are even thirds because nothing records how long he spent at each level yet. '
      + 'They will be sized by real seasons as soon as that is written down.'));
  }

  /* Then the same thing in words, level by level, with the transition in between. */
  const list = el('div', { class: 'cv-timeline' });
  track.forEach((t, i) => {
    if (i) list.append(transitionRow(track[i - 1], t, character));
    list.append(levelRow(t));
  });
  card.append(list);

  return card;
}

function levelRow(t) {
  const box = el('div', { class: `cv-tl-level is-${t.state}` });
  const head = el('div', { class: 'cv-tl-head' },
    el('b', {}, t.label),
    el('span', { class: 'cv-pill' },
      t.state === 'now' ? 'here now' : t.state === 'done' ? 'been there' : 'not yet'));
  box.append(head);

  const lines = [];
  if (t.row) {
    const span = [t.row.from_season, t.row.to_season].filter(Boolean).join(' to ');
    if (span) lines.push(`Seasons ${span}.`);
    const ages = [t.row.from_age, t.row.to_age].filter((v) => v !== null && v !== undefined);
    if (ages.length === 2) lines.push(`Ages ${ages[0]} to ${ages[1]}.`);
    if (t.row.team_abbrev) lines.push(`Played for ${t.row.team_abbrev}.`);
    /* WHAT HE WAS PAID AT THIS LEVEL. `finances` is recorded on the open level row by the
       weekly sync, so a level he has left keeps the last figure it saw - which is the right
       thing for a career page: it is a record of what he earned there, not a live quote.
       The band is read, never recomputed; it is a percentile against his own league and
       `points.payout_band` is the only implementation of that rule. */
    const f = t.row.finances;
    if (f && f.salary) {
      const cash = '$' + Math.round(f.salary).toLocaleString('en-US');
      lines.push(f.band ? `Earned ${cash} a year - ${f.band} money.`
        : `Earned ${cash} a year.`);
      if (f.payout != null) lines.push(`That paid him ${f.payout} skill points a season.`);
    } else if (f) {
      lines.push('No contract on file at this level.');
    }
    if (t.row.how_it_ended) lines.push(String(t.row.how_it_ended));
  } else if (t.state === 'now') {
    lines.push(t.team ? `On ${t.team}.` : 'Waiting for a roster spot.');
    if (t.season) lines.push(`Season ${t.season}, and he is ${t.age}.`);
    lines.push(`This level runs ages ${t.ages[0]} to ${t.ages[1] || 'however long he lasts'}.`);
  } else if (t.state === 'done') {
    lines.push('He came through here - that much follows from where he is now.');
    lines.push('Which team, and which seasons, is not written down anywhere yet.');
  } else {
    lines.push(t.blurb);
  }

  for (const line of lines) box.append(el('p', {}, line));
  return box;
}

/**
 * What moved him from one level to the next. A promotion is not a trade: the three leagues live
 * in three separate saves, so the move is a reserve slot claimed in the destination save and the
 * character stamped onto it (CONVENTIONS.md, "Cheezeyverse layout"). Nothing records when that
 * happened, or what pick he went at, so this says which of the two doors he went through and is
 * honest about the rest.
 */
function transitionRow(from, to, character) {
  const happened = to.state !== 'ahead';
  const wire = el('div', { class: `cv-tl-move${happened ? ' is-done' : ''}` });

  let text;
  if (from.key === 'prep') {
    text = happened
      ? 'Moved up to College - either he declared, or he finished his age-17 season and aged out.'
      : 'Next: declare for the college draft, or finish his age-17 season and go up anyway.';
  } else {
    const pick = draftLine(character);
    text = happened
      ? (pick || 'Drafted into the pros. Which round and which pick is not recorded yet.')
      : 'Next: declare for the pro draft, or use up his four years of eligibility first.';
  }
  wire.append(el('span', { class: 'cv-tl-arrow' }, '↓'), el('span', {}, text));
  return wire;
}

/** `draft_round` / `draft_pick` / `draft_season` are the columns that would fill this in. */
function draftLine(character) {
  const pick = Number(character.draft_pick);
  if (!Number.isFinite(pick)) return null;
  const round = Number(character.draft_round);
  const season = character.draft_season;
  return `Drafted ${ordinal(pick)}${Number.isFinite(round) ? ` in round ${round}` : ''}`
    + `${season ? `, ${season}` : ''}.`;
}

function ordinal(n) {
  const v = Math.abs(Math.round(Number(n)));
  const tens = v % 100;
  if (tens >= 11 && tens <= 13) return `${v}th`;
  return `${v}${['th', 'st', 'nd', 'rd'][v % 10] || 'th'}`;
}

