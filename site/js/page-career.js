async function boot() {
  const user = await currentUser();
  const profile = user ? await ensureProfile() : null;
  chrome.refresh(user, profile);

  const cfg = await settings();

  /* A bogus ?id= is the ordinary case, not an emergency. An id that is simply absent comes back
     as null; one that is not even a uuid makes Postgres raise, and that is still just a bad
     link, so both land on the same page. */
  let character = null;
  let why = null;
  try {
    character = await characterById(wantedId);
  } catch (err) {
    why = errorText(err);
  }
  $('#loading').hidden = true;

  if (!character) {
    notFound(why);
    return;
  }

  /* upgrade_requests and point_ledger are readable only by the character's owner (the RLS
     policies in schema.sql), so a visitor gets an empty list rather than an error. Ask for them
     only when the viewer actually is the owner, and say so on the page when he is not. */
  const mine = !!user && user.id === character.owner;
  const storiesPromise = freshJSON('data/stories.json');
  const [requests, ledger, stories] = mine
    ? await Promise.all([requestsFor([character.id]), ledgerFor([character.id]), storiesPromise])
    : [[], [], await storiesPromise];

  render({
    character,
    requests,
    ledger,
    season: Number(cfg.current_season) || null,
    viewerOwns: mine,
    preview: false,
    stories,
  });
}

