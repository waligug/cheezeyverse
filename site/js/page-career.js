/**
 * ui.js's el() builds with document.createElement, which cannot make an SVG node - it would
 * return an HTMLUnknownElement that lays out as an empty box and renders nothing at all. So SVG
 * gets its own two-line builder rather than a reimplementation of anything in ui.js.
 */
function svg(tag, attrs, ...kids) {
  const node = document.createElementNS(SVGNS, tag);
  for (const [k, v] of Object.entries(attrs || {})) {
    if (v === null || v === undefined || v === false) continue;
    node.setAttribute(k, v === true ? '' : String(v));
  }
  for (const kid of kids.flat()) {
    if (kid === null || kid === undefined || kid === false) continue;
    node.append(kid instanceof Node ? kid : document.createTextNode(String(kid)));
  }
  return node;
}

/** A plain x/y line chart. Used by the two sections that have dated history to draw. */
function lineChart(points, label, fmtX, { zeroBased = true } = {}) {
  const W = 560;
  const H = 170;
  const padL = 44;
  const padR = 14;
  const padT = 14;
  const padB = 26;
  const xs = points.map((p) => p.x);
  const ys = points.map((p) => p.y);
  const xLo = Math.min(...xs);
  const xHi = Math.max(...xs);
  // Anchoring at zero is right for "points applied", where zero means none. It is wrong for a
  // rating average: a line moving 25 to 29 over a season is the whole story, and squashed into
  // the top seventh of a chart that starts at zero it looks like nothing happened at all.
  const yLo = zeroBased ? Math.min(0, ...ys) : Math.min(...ys) - 2;
  const yHi = Math.max(...ys) || 1;
  const x = (v) => padL + (xHi === xLo ? 0.5 : (v - xLo) / (xHi - xLo)) * (W - padL - padR);
  const y = (v) => padT + (1 - (v - yLo) / (yHi - yLo || 1)) * (H - padT - padB);

  const root = svg('svg', {
    class: 'cv-chart', viewBox: `0 0 ${W} ${H}`, preserveAspectRatio: 'xMidYMid meet',
    role: 'img', 'aria-label': label,
  });
  for (const v of [yLo, (yLo + yHi) / 2, yHi]) {
    root.append(svg('line', { x1: padL, x2: W - padR, y1: y(v), y2: y(v), class: 'cv-chart-grid' }));
    root.append(svg('text', {
      x: padL - 6, y: y(v) + 4, class: 'cv-chart-label', 'text-anchor': 'end',
    }, String(Math.round(v))));
  }
  root.append(svg('line', {
    x1: padL, x2: W - padR, y1: H - padB, y2: H - padB, class: 'cv-chart-axis',
  }));
  const show = fmtX || ((v) => String(v));
  root.append(svg('text', {
    x: padL, y: H - padB + 16, class: 'cv-chart-label', 'text-anchor': 'start',
  }, show(xLo)));
  root.append(svg('text', {
    x: W - padR, y: H - padB + 16, class: 'cv-chart-label', 'text-anchor': 'end',
  }, show(xHi)));
  root.append(svg('polyline', {
    class: 'cv-chart-line', points: points.map((p) => `${x(p.x)},${y(p.y)}`).join(' '),
  }));
  for (const p of points) {
    root.append(svg('circle', { cx: x(p.x), cy: y(p.y), r: 3.5, class: 'cv-chart-dot' }));
  }
  return el('div', { class: 'cv-chart-wrap' }, root);
}

/* ------------------------------------------------------------------------------- bits */

function mean(values) {
  const list = (values || []).filter((v) => Number.isFinite(v));
  return list.length ? list.reduce((a, b) => a + b, 0) / list.length : NaN;
}

/**
 * How old he is in game years.
 *
 * Deliberately uses getUTCFullYear, because ui.js's heightNow() does: if the two disagreed by a
 * year the header height and the last point on the chart would disagree with each other.
 * Not clamped at the top - a pro can be thirty - but the height model is, inside heightAtAge.
 */
function ageOf(character, season) {
  if (!character.game_dob || !season) return START_AGE;
  const born = new Date(character.game_dob).getUTCFullYear();
  const age = Number(season) - born;
  return Number.isFinite(age) ? Math.max(START_AGE, age) : START_AGE;
}

