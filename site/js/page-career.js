/* career.html?id=<character-id> - one character, followed from Prep through College to Pro.

   WHY THIS PAGE EXISTS
   Each league's site is generated by FBPB3 and only knows about its own save. A character who
   goes Prep -> College -> Pro therefore has three unconnected sets of pages under three
   different in-game player ids, and nothing in the game ties them together. The one thing that
   does span all three is the character row itself, so this page is built from that row and says
   plainly where the game's own record stops.

   WHAT IS HONEST HERE, AND WHY
   The row carries who he is (identity, quiz, traits, the height model's inputs) and what he is
   RIGHT NOW (ratings, potentials, league, team). It carries no history at all: no per-season
   stats, no record of which team he was on at a level he has left, no snapshot of his sheet at
   any past date. So every section that would need history either reconstructs what is genuinely
   derivable or says out loud that the data is not written yet. Nothing on this page is invented.

   Three reconstructions do real work, and all three are exact rather than approximate:
     * HIS SHEET AT FOURTEEN is re-derived with rules.startingSheet() from the stored `traits`,
       `position`, `quiz_answers.summer` and the identity seed. It is the same pure function the
       create page ran, fed the stored trait vector rather than re-scoring the quiz, so it cannot
       drift if the quiz is ever retuned. See startingSheetOf() for the one way it can go wrong.
     * HIS HEIGHT AT EVERY AGE comes from rules.growthCurve(), which is the same model
       commissioner/growth.py writes into league.dat. Only the offseasons that have happened are
       drawn, for the reason page-me.js gives: the rest of the curve is already decided but
       printing it hands back the number the whole creation design withholds.
     * WHAT HE WAS CALLED THEN is the stored `archetype`; what he reads as now is
       rules.classify() over the live sheet.

   The arc renders from `character.level_history` when that column exists and falls back to what
   can be inferred from his age and current league when it does not, so the day the commissioner
   starts writing it the timeline fills in rather than needing a rewrite. Same for
   `league_player_ids`, `draft_pick` and `rating_snapshots` - each has a reader here already.

   Preview mode: with no Supabase this renders a clearly-marked example character, the same way
   create.html does, so the layout can be seen and demoed. The example is built as a snake_case
   row and goes through exactly the same code path a real row does. */

