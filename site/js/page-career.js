/**
 * His sheet on the day he was made, re-derived rather than stored.
 *
 * rules.startingSheet() is pure, so feeding it the stored trait vector, his listed position, the
 * summer out of `quiz_answers` and the identity seed reproduces exactly the numbers create.html
 * inserted. The stored `traits` is used in preference to re-scoring `quiz_answers`, so a future
 * retune of the quiz cannot silently change what his past looked like.
 *
 * THE ONE WAY THIS GOES WRONG: the seed is identitySeed(first, last, hometown, jersey), and
 * schema.sql lets an owner update first_name and last_name. Rename a character and the seed
 * changes, so this reconstruction quietly becomes a different fourteen year old. A
 * `starting_ratings` / `starting_potentials` snapshot written at creation is the fix; until then
 * the page says which it is showing.
 */
function startingSheetOf(character) {
  const traits = character.traits;
  if (!traits || !Object.keys(traits).length) return null;
  if (!character.position) return null;
  const seed = identitySeed({
    firstName: character.first_name,
    lastName: character.last_name,
    hometown: character.hometown,
    jersey: character.jersey_preference,
  });
  try {
    return startingSheet(character.position, traits, {
      summer: (character.quiz_answers || {}).summer,
      seed,
    });
  } catch (err) {
    console.warn('could not re-derive the starting sheet', err);
    return null;
  }
}

