/** One row's story as a bar: where he started, where he is, where his ceiling is. */
function barPair(was, is, pot) {
  const pct = (v) => Math.max(0, Math.min(100, (100 * (Number(v) || 0)) / RATING_MAX));
  const bar = el('span', { class: 'cv-bar cv-bar-inline' },
    el('i', { style: `width:${pct(is)}%` }));
  if (Number.isFinite(Number(was))) {
    bar.append(el('s', {
      style: `left:0;width:${Math.max(1, pct(was))}%`,
      title: `he started at ${was}`,
    }));
  }
  if (Number.isFinite(Number(pot))) {
    bar.append(el('u', { style: `left:${pct(pot)}%`, title: `potential ${pot}` }));
  }
  return bar;
}

